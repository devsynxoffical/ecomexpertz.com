// Map of platform logo components
export const PlatformLogo = ({ platform = 'ebay', size = 36, className = '' }) => {
  const norm = (platform || '').toLowerCase();
  if (norm.includes('walmart')) return <WalmartLogo size={size} className={className} />;
  if (norm.includes('temu')) return <TemuLogo size={size} className={className} />;
  if (norm.includes('amazon')) return <AmazonLogo size={size} className={className} />;
  if (norm.includes('aliexpress')) return <AliExpressLogo size={size} className={className} />;
  if (norm.includes('target')) return <TargetLogo size={size} className={className} />;
  if (norm.includes('shopify')) return <ShopifyLogo size={size} className={className} />;
  if (norm.includes('shopee')) return <ShopeeLogo size={size} className={className} />;
  return <EbayLogo size={size} className={className} />;
};
